"""Keep ``po/`` in step with the code: extract the messages, merge them, compile catalogs.

Run from a checkout::

    uv run --frozen python -m shidashi.i18n_catalog update            # po/shidashi.pot + po/*.po
    uv run --frozen python -m shidashi.i18n_catalog compile build/locale

The messages come from two places:

* the help of the built Click tree -- every docstring, ``help=`` and help panel that
  ``shidashi ... --help`` can show, read from the very objects
  :mod:`shidashi.i18n_help` translates, so the two cannot disagree;
* the source of the ``shidashi`` package, parsed with :mod:`ast`: every literal passed
  to ``i18n.t``, ``i18n.mark`` or ``i18n.tn`` (see :mod:`shidashi.i18n`).

``tests/test_i18n_catalogs.py`` fails when ``po/`` is stale, so a changed message
cannot be committed without ``update``.
"""

import ast
import inspect
import sys
from pathlib import Path
from typing import Any

import typer.main

from shidashi import i18n, i18n_help, i18n_po

PACKAGE_DIR = Path(__file__).resolve().parent
REPO_DIR = PACKAGE_DIR.parent

POT_HEADER = (
    "Project-Id-Version: shidashi\n"
    "MIME-Version: 1.0\n"
    "Content-Type: text/plain; charset=UTF-8\n"
    "Content-Transfer-Encoding: 8bit\n"
)
POT_COMMENT = (
    "Translatable messages of Shidashi.\n"
    'Generated by "python -m shidashi.i18n_catalog update"; do not edit by hand.'
)

# The i18n functions whose literal arguments are messages, and how many they take.
_MARKERS = {"t": 1, "mark": 1, "tn": 2}


def _rel(path: str | Path) -> str:
    return Path(path).resolve().relative_to(REPO_DIR).as_posix()


def _literal(node: ast.expr) -> str | None:
    """Evaluate a string literal or an implicit/``+`` concatenation of them."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _literal(node.left), _literal(node.right)
        if left is not None and right is not None:
            return left + right
    return None


def source_messages(package_dir: Path = PACKAGE_DIR) -> list[i18n_po.Entry]:
    """Return the messages marked in the package's source, by file then position.

    A non-literal argument to ``i18n.mark`` or ``i18n.tn`` raises :class:`ValueError`
    (a computed msgid can never be found in a catalog); to ``i18n.t`` it is skipped, as
    it translates text marked where it was declared.
    """
    found: list[i18n_po.Entry] = []
    for path in sorted(package_dir.glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), str(path))
        calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call)]
        calls.sort(key=lambda node: (node.lineno, node.col_offset))
        for call in calls:
            func = call.func
            if not (
                isinstance(func, ast.Attribute)
                and isinstance(func.value, ast.Name)
                and func.value.id == "i18n"
                and func.attr in _MARKERS
            ):
                continue
            where = f"{_rel(path)}:{call.lineno}"
            literals = [_literal(arg) for arg in call.args[: _MARKERS[func.attr]]]
            if any(value is None for value in literals):
                if func.attr == "t":
                    continue
                raise ValueError(f"{where}: i18n.{func.attr} needs string literals")
            texts = [value for value in literals if value is not None]
            if len(texts) != _MARKERS[func.attr] or not all(texts):
                raise ValueError(f"{where}: i18n.{func.attr} of an empty or missing message")
            found.append(
                i18n_po.Entry(
                    msgid=texts[0],
                    plural=texts[1] if func.attr == "tn" else "",
                    refs=[_rel(path)],
                    brace_format=bool(i18n_po.FIELD_RE.search("".join(texts))),
                )
            )
    return found


def _command_file(command: Any) -> str:
    callback = getattr(command, "callback", None)
    target = inspect.unwrap(callback) if callback is not None else None
    try:
        source = inspect.getsourcefile(target) if target is not None else None
    except TypeError:
        source = None
    return _rel(source) if source else _rel(PACKAGE_DIR / "cli.py")


def help_messages() -> list[i18n_po.Entry]:
    """Return every help text of the built Click tree, in the order ``--help`` walks it."""
    from shidashi.cli import app  # here, not at the top: cli imports half the package

    root = typer.main.get_command(app)
    found: list[i18n_po.Entry] = []
    for command in i18n_help.walk_commands(root):
        ref = _command_file(command)
        texts = [command.help, command.short_help, command.epilog]
        for param in command.params:
            texts += [getattr(param, "help", None), getattr(param, "rich_help_panel", None)]
        found += [i18n_po.Entry(msgid=text, refs=[ref]) for text in texts if text]
    return found


def extract() -> list[i18n_po.Entry]:
    """Return every message, unique by msgid, its references merged and sorted."""
    by_id: dict[str, i18n_po.Entry] = {}
    for entry in [*help_messages(), *source_messages()]:
        known = by_id.get(entry.msgid)
        if known is None:
            by_id[entry.msgid] = entry
            continue
        if known.plural != entry.plural:
            # gettext keys an entry by its msgid alone: it is plain or plural, never both.
            raise ValueError(f"{entry.refs[0]}: {entry.msgid!r} is used with two plural forms")
        known.refs = sorted({*known.refs, *entry.refs})
        known.brace_format = known.brace_format or entry.brace_format
    return list(by_id.values())


def linguas(po_dir: Path) -> list[str]:
    """Return the languages ``po/LINGUAS`` lists (gettext names: ``pt_BR``, ``zh_CN``)."""
    lines = (po_dir / "LINGUAS").read_text(encoding="utf-8").splitlines()
    return [word for line in lines if not line.startswith("#") for word in line.split()]


def update(po_dir: Path) -> list[Path]:
    """Rewrite ``shidashi.pot`` from the code and merge it into every ``<lang>.po``.

    Returns the files that changed.
    """
    template = extract()
    changed: list[Path] = []
    pot = po_dir / f"{i18n.DOMAIN}.pot"
    if i18n_po.write_if_changed(pot, i18n_po.render(POT_HEADER, POT_COMMENT, template, 2)):
        changed.append(pot)
    for lang in linguas(po_dir):
        path = po_dir / f"{lang}.po"
        text = path.read_text(encoding="utf-8")
        header, old = i18n_po.parse(text)
        comment = "\n".join(
            line.removeprefix("#").strip() for line in text.splitlines() if line.startswith("# ")
        )
        nplurals = i18n_po.nplurals_of(header)
        merged = i18n_po.merge(template, old, nplurals)
        if i18n_po.write_if_changed(path, i18n_po.render(header, comment, merged, nplurals)):
            changed.append(path)
    return changed


def compile_catalogs(po_dir: Path, out_dir: Path) -> list[Path]:
    """Compile every ``<lang>.po`` to ``<out_dir>/<lang>/LC_MESSAGES/shidashi.mo``."""
    written: list[Path] = []
    for lang in linguas(po_dir):
        header, entries = i18n_po.parse((po_dir / f"{lang}.po").read_text(encoding="utf-8"))
        target = out_dir / lang / "LC_MESSAGES" / f"{i18n.DOMAIN}.mo"
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(f".{target.name}.tmp")
        tmp.write_bytes(i18n_po.compile_mo(header, entries))
        tmp.replace(target)
        written.append(target)
    return written


def run(argv: list[str]) -> int:
    """The ``python -m shidashi.i18n_catalog`` command line; returns the exit status."""
    po_dir = REPO_DIR / "po"
    if argv == ["update"]:
        for path in update(po_dir):
            print(f"updated {_rel(path)}", file=sys.stderr)
        return 0
    if len(argv) == 2 and argv[0] == "compile":
        for path in compile_catalogs(po_dir, Path(argv[1])):
            print(f"compiled {path}", file=sys.stderr)
        return 0
    print("usage: python -m shidashi.i18n_catalog update | compile OUT_DIR", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(run(sys.argv[1:]))
